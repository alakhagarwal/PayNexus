package com.paynexus.walletservice.dto.request;

import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.Digits;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.math.BigDecimal;
import java.util.UUID;

@Getter
@Setter
@NoArgsConstructor
public class P2PTransferRequest {

    @NotNull(message = "Sender ID is required")
    private UUID senderId;

    @NotNull(message = "Receiver ID is required")
    private UUID receiverId;

    /**
     * Amount in INR.
     * - Minimum ₹1.00 to prevent zero/negative-amount exploits.
     * - Maximum 2 decimal places (paise precision).
     */
    @NotNull(message = "Amount is required")
    @DecimalMin(value = "1.00", message = "Minimum transfer amount is ₹1.00")
    @Digits(integer = 10, fraction = 2, message = "Amount must have at most 2 decimal places")
    private BigDecimal amount;

    /**
     * 6-digit transaction PIN to authorize the transfer.
     * Required — no transfer happens without PIN verification.
     */
    @NotBlank(message = "Transaction PIN is required")
    @lombok.NonNull
    private String transactionPin;

    /**
     * Idempotency key — a UUID generated by the client (frontend/mobile app).
     * If the same key is sent twice within 120 seconds, the second request is rejected.
     * This prevents accidental double-transfers due to network retries or double-clicks.
     */
    @NotBlank(message = "Idempotency-Key header is required")
    private String idempotencyKey;
}
